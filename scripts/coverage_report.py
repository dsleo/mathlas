#!/usr/bin/env python3
"""Coverage report for data/events.json: a worklist of source-first events and
counts by field and century. Prints the report and writes
research/enrichment/coverage_report.md. Stdlib only.

Rank = inbound links (distinct other events pointing here) + 2 x weakness. Weakness
sums, over the event's first_statement milestones: 2 if confidence is low, 1 if
medium; plus 1 if none of its evidence is a bibliographic record or primary text
(history pages only); plus 1 if the event's map date is approximate. Highly linked
events with the weakest first statements are the ones a wrong date would mislead most.
"""

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research/enrichment/coverage_report.md"
STRONG = {"bibliographic_record", "primary_text", "primary_publication"}


def century(y):
    return f"{-((max(-y, 1) - 1) // 100 + 1)}" if y <= 0 else f"{(y - 1) // 100 + 1}"


def weakness(e):
    fs = [m for m in e["ms"] if m["r"] == "first_statement"]
    w = max((2 if m["c"] == "low" else 1 if m["c"] == "medium" else 0 for m in fs), default=2)
    if not any(x.get("k") in STRONG for m in fs for x in m["ev"]):
        w += 1
    return w + bool(e.get("approx"))


def label(c):
    n = int(c)
    return f"{-n} BCE" if n < 0 else f"{n} CE"


def main():
    events = json.loads((ROOT / "data/events.json").read_text())
    inbound = Counter()
    for e in events:
        for links in e["rel"].values():
            for target in {link["p"] for link in links}:
                inbound[target] += 1  # e links to target; reciprocity is enforced by the validator

    rows = []
    for e in events:
        if e["tier"] != "source-first":
            continue
        w = weakness(e)
        rows.append((inbound[e["pid"]] + 2 * w, inbound[e["pid"]], w, e))
    rows.sort(key=lambda r: (-r[0], -r[1], r[3]["pid"]))

    tiers = Counter(e["tier"] for e in events)
    lines = ["# Coverage report", "", "Generated by `python3 scripts/coverage_report.py` from `data/events.json`. Do not edit by hand.", "",
             f"{len(events)} events: " + ", ".join(f"{n} {t}" for t, n in tiers.most_common()) + ".", "",
             "## Source-first worklist", "",
             "Score = inbound links from other events + 2 x weakness (low/medium confidence on a first statement, no bibliographic or primary source, approximate date).", "",
             "| Rank | pid | Event | Field | Year | Inbound | Weakness | Score |", "|---|---|---|---|---|---|---|---|"]
    for i, (score, n, claim, e) in enumerate(rows, 1):
        lines.append(f"| {i} | {e['pid']} | {e['name'].replace('|', '/')} | {e['cl']} | {e['y']} | {n} | {claim} | {score} |")

    def table(title, counts, key):
        out = ["", f"## Events per {title}", "", f"| {title.capitalize()} | All | Direct | Source-first |", "|---|---|---|---|"]
        for k in sorted(counts, key=key):
            c = counts[k]
            out.append(f"| {k if title == 'field' else label(k)} | {c['all']} | {c['direct']} | {c['source-first']} |")
        return out

    by_field, by_century = {}, {}
    for e in events:
        for bucket, k in ((by_field, e["cl"]), (by_century, century(e["y"]))):
            c = bucket.setdefault(k, Counter())
            c["all"] += 1
            c[e["tier"]] += 1
    lines += table("field", by_field, lambda k: (-by_field[k]["all"], k))
    lines += table("century", by_century, int)

    lines += ["", "## Traditions", "",
              "No field in `data/events.json` records the mathematical tradition (Greek, Chinese, Indian, Islamic, European, ...). "
              "`cat` is the harvest batch, `cl` the field and `from`/`to` the subjects, so a tradition breakdown cannot be computed without guessing from names. "
              "An optional `trad` tag is proposed in `research/enrichment/MILESTONE_SCHEMA.md`; events are not mass-tagged."]

    text = "\n".join(lines) + "\n"
    OUT.write_text(text)
    print(text, end="")


if __name__ == "__main__":
    main()
